#!/usr/bin/env node
/*
 * Generates the search-engine parts of the site from index.html:
 *  - the <head> SEO block of every page (title, description, canonical,
 *    hreflang links, Open Graph / Twitter tags, JSON-LD),
 *  - the Help, Notes, About and NASA texts written into the HTML, so they
 *    can be read without JavaScript,
 *  - one page per language: de/, nl/, tr/, es/ (the root page is English),
 *  - sitemap.xml.
 *
 * index.html is the template: edit it, then run `node tools/build-pages.js`.
 */
'use strict';
const fs = require('fs');
const path = require('path');
const I18N = require('../js/i18n.js');

const BASE = 'https://ehcrea.github.io/vacuum-chamber-calculator/';
const ROOT = path.join(__dirname, '..');
const LANGS = Object.keys(I18N.LANGS); // en first
const OG_LOCALE = { en: 'en_US', de: 'de_DE', nl: 'nl_NL', tr: 'tr_TR', es: 'es_ES' };
const META = I18N.meta();
const HTML = I18N.html();
const DICT = I18N.dict();

const url = (l) => BASE + (l === 'en' ? '' : l + '/');
const escAttr = (s) => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const decode = (s) => s.replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&amp;/g, '&');
const escText = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

function seoBlock(l) {
  const title = META.title[l];
  const desc = META.description[l];
  const ld = {
    '@context': 'https://schema.org',
    '@type': 'WebApplication',
    name: 'Vacuum Chamber Calculator',
    alternateName: title,
    url: url(l),
    description: desc,
    applicationCategory: 'EngineeringApplication',
    operatingSystem: 'Any (web browser)',
    browserRequirements: 'Requires JavaScript',
    inLanguage: LANGS,
    isAccessibleForFree: true,
    offers: { '@type': 'Offer', price: '0', priceCurrency: 'EUR' },
    license: 'https://opensource.org/licenses/MIT',
    image: BASE + 'icons/og-image.png',
    author: { '@type': 'Person', name: 'E. Tozlu', url: 'https://erentozlu.com' },
    publisher: { '@type': 'Organization', name: 'ehcrea', url: 'https://ehcrea.com' },
    codeRepository: 'https://github.com/ehcrea/vacuum-chamber-calculator',
  };
  const lines = [
    `<title>${escText(title)}</title>`,
    `<meta name="description" content="${escAttr(desc)}">`,
    `<link rel="canonical" href="${url(l)}">`,
    ...LANGS.map((x) => `<link rel="alternate" hreflang="${x}" href="${url(x)}">`),
    `<link rel="alternate" hreflang="x-default" href="${url('en')}">`,
    `<meta property="og:type" content="website">`,
    `<meta property="og:site_name" content="ehcrea">`,
    `<meta property="og:title" content="${escAttr(title)}">`,
    `<meta property="og:description" content="${escAttr(desc)}">`,
    `<meta property="og:url" content="${url(l)}">`,
    `<meta property="og:image" content="${BASE}icons/og-image.png">`,
    `<meta property="og:image:width" content="1200">`,
    `<meta property="og:image:height" content="630">`,
    `<meta property="og:image:alt" content="${escAttr(title)}">`,
    `<meta property="og:locale" content="${OG_LOCALE[l]}">`,
    ...LANGS.filter((x) => x !== l).map((x) => `<meta property="og:locale:alternate" content="${OG_LOCALE[x]}">`),
    `<meta name="twitter:card" content="summary_large_image">`,
    `<meta name="twitter:title" content="${escAttr(title)}">`,
    `<meta name="twitter:description" content="${escAttr(desc)}">`,
    `<meta name="twitter:image" content="${BASE}icons/og-image.png">`,
    `<script type="application/ld+json">${JSON.stringify(ld).replace(/</g, '\\u003c')}</script>`,
  ];
  return '<!-- seo: generated by tools/build-pages.js -->\n  ' + lines.join('\n  ') + '\n  <!-- /seo -->';
}

/** Translate text nodes and title/aria-label/placeholder attributes of the body. */
function translateBody(body, l) {
  const d = DICT[l];
  body = body.replace(/>([^<>]+)</g, (m, raw) => {
    const en = decode(raw.trim());
    if (!en || d[en] === undefined) return m;
    const lead = raw.match(/^\s*/)[0], trail = raw.match(/\s*$/)[0];
    return '>' + lead + escText(d[en]) + trail + '<';
  });
  return body.replace(/\b(title|aria-label|placeholder)="([^"]*)"/g, (m, a, v) => {
    const en = decode(v);
    return d[en] === undefined ? m : `${a}="${escAttr(d[en])}"`;
  });
}

function build(template, l) {
  let s = template;
  s = s.replace(/<!-- seo: generated[\s\S]*?<!-- \/seo -->/, seoBlock(l));
  s = s.replace(/<html lang="\w+" data-page="\w+">/, `<html lang="${l}" data-page="${l}">`);
  s = s.replace(/<!--i18n:(\w+)-->[\s\S]*?<!--\/i18n:\1-->/g, (m, k) => {
    if (!HTML[k]) throw new Error('Unknown HTML block ' + k);
    return `<!--i18n:${k}-->${HTML[k][l] || HTML[k].en}<!--/i18n:${k}-->`;
  });
  if (l !== 'en') {
    s = s.replace(/\b(href|src)="(icons\/|css\/|js\/|manifest\.webmanifest)/g, '$1="../$2');
    const i = s.indexOf('<body');
    const head = s.slice(0, i);
    let body = s.slice(i);
    // Leave the scripts alone, translate the rest of the body.
    const j = body.indexOf('<script');
    body = translateBody(body.slice(0, j), l) + body.slice(j);
    s = head + body;
  }
  return s;
}

const template = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
for (const l of LANGS) {
  const out = build(template, l);
  const file = l === 'en' ? path.join(ROOT, 'index.html') : path.join(ROOT, l, 'index.html');
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, out);
  console.log('wrote', path.relative(ROOT, file));
}

const today = new Date().toISOString().slice(0, 10);
const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">
${LANGS.map((l) => `  <url>
    <loc>${url(l)}</loc>
    <lastmod>${today}</lastmod>
${LANGS.map((x) => `    <xhtml:link rel="alternate" hreflang="${x}" href="${url(x)}"/>`).join('\n')}
    <xhtml:link rel="alternate" hreflang="x-default" href="${url('en')}"/>
  </url>`).join('\n')}
</urlset>
`;
fs.writeFileSync(path.join(ROOT, 'sitemap.xml'), sitemap);
console.log('wrote sitemap.xml');
